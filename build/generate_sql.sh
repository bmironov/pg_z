#!/usr/bin/env bash

PREFIX=$1

# Fail rest of the script at first error
set -e

if [ "$CONFIGURE_RUN" = "yes" ]; then
    echo "-- Autogenerated by Makefile, do not edit" >$DATA
    echo '\echo Use "CREATE EXTENSION pg_z" to load this file. \quit' >>$DATA
    cat ${PREFIX}/sql/core_add.sql >>$DATA
    for algo in $ACTIVE_ALGOS; do
        if [ -f "${PREFIX}/sql/${algo}_add.sql" ]; then
            echo "" >>$DATA
            echo "-- =========================================" >>$DATA
            echo "-- $algo Functions" >>$DATA
            echo "-- =========================================" >>$DATA
            cat "${PREFIX}/sql/${algo}_add.sql" >>$DATA
        fi
    done
fi

exit 0
