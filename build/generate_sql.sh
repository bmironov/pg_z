#!/usr/bin/env bash

TOP_DIR=$1
OUT=${TOP_DIR}/${DATA}

# Fail rest of the script at first error
set -e

if [ "$CONFIGURE_RUN" = "yes" ]; then
    echo "-- Autogenerated by Makefile, do not edit" >$OUT
    echo '\echo Use "CREATE EXTENSION pg_z" to load this file. \quit' >>$OUT
    cat ${TOP_DIR}/sql/core_add.sql >>$OUT
    for algo in $ACTIVE_ALGOS; do
        if [ -f "${TOP_DIR}/sql/${algo}_add.sql" ]; then
            echo "" >>$OUT
            echo "-- =========================================" >>$OUT
            echo "-- $algo Functions" >>$OUT
            echo "-- =========================================" >>$OUT
            cat "${TOP_DIR}/sql/${algo}_add.sql" >>$OUT
        fi
    done
fi

exit 0
